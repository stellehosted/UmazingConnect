// Artwork exported directly from the "Logo" group in The Compass.sketch.
// The viewBox matches that group's own 2380x2380 bounding box, so one SVG
// unit equals one unit of the 1920x1080 landing frame it's placed on.
//
// Twelve ticks: four cardinal marks, plus two rotated sets of four diagonal
// marks that together make a 12-position dial.

const VIEWBOX = 2380
const DIAL_CX = 1190
const DIAL_CY = 1427.09355

// The exported needle is drawn resting toward the north-east, so every
// rotation is measured relative to that.
const NEEDLE_REST_ANGLE = 40.72

// A lightly underdamped spring: it overshoots the cursor by a few degrees and
// settles, the way a real magnetic needle would, rather than snapping there.
const SPRING_STIFFNESS = 120
const SPRING_DAMPING = 18
const FIXED_DT = 1 / 60

function stepNeedle(state: { angle: number; velocity: number }, target: number) {
  const acceleration = SPRING_STIFFNESS * (target - state.angle) - SPRING_DAMPING * state.velocity
  state.velocity += acceleration * FIXED_DT
  state.angle += state.velocity * FIXED_DT
}

